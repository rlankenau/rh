#!/usr/bin/env python3
"""Scan extracted paper text for marks of unfinished writing.

Usage: tools/pdftext PAPER.pdf 1 940 > all.txt ; python3 tools/gapscan.py all.txt > notes/masullo-gaps.md

Looks for undefined cross-references ("??"), section headings with no text under them, and
footnotes that read as editing notes. It matches patterns in extracted text, so it cannot
see a gap that is not marked.
"""
import re, sys

text = open(sys.argv[1]).read()
parts = re.split(r"=== page (\d+) ===\n", text)[1:]
pages = {int(parts[i]): parts[i + 1] for i in range(0, len(parts), 2)}
HEADING = re.compile(r"^(\d{1,2}|[A-E])\.\d+(\.\d+)?\. [A-Z“].{3,110}$")
NOTE = re.compile(r"^\d{1,2}(Add|Insert|Correct|State|Prove|Fix|Explain|Complete|Write|Check|Expand|Include|"
                  r"Mention|Rewrite|Remove|Give|Finish|Revise|Clarify|Justify|Must|Maybe|Is |Does |There |This )\b.*$", re.M)
QUERY = re.compile(r"(?i)finish|correct|insert|include|rewrite|expand|clarif|reference|\?$|needs|must|check|complete")

print("# Unfinished parts found by text scan\n")
print("Source: the-music-of-the-primes.pdf, release of 2026-11-20. Generated by tools/gapscan.py.\n")
print("## Undefined cross-references\n")
for p, s in pages.items():
    for m in re.finditer(r"(Theorem|Lemma|Definition|Chapter|Caveat|Remark|§|\() ?\?\?", s):
        ctx = s[max(0, m.start() - 80):m.end() + 30].replace("\n", " ")
        print(f"- p. {p}: …{ctx}…")
print("\n## Section headings with no text under them\n")
for p in range(11, 933):
    lines = [l for l in pages.get(p, "").split("\n") if l.strip()]
    for a, b in zip(lines, lines[1:]):
        if HEADING.match(a) and HEADING.match(b) and not re.search(r"\d+$", a):
            # a heading followed by its own first subsection is not empty
            if not b.startswith(a.split(" ")[0]):
                print(f"- p. {p}: {a}")
print("\n## Footnotes that read as editing notes\n")
for p, s in pages.items():
    for m in NOTE.finditer(s):
        if QUERY.search(m.group(0)):
            print(f"- p. {p}: {m.group(0)[:200]}")
